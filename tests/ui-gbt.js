/* Сценарии интерфейса: адрес GB/T28181 в мастере «По адресу» — разбор строки
   [gbt://]deviceID[/порт видео]@serverID[-локальный IP[/внешний IP]] (Axxon One, «Connecting cameras via the GB/T28181
   protocol») и один SIP-сервер на все устройства GB/T сервера: сверка с GET /units?q=GBT28181&fields=vendor и строками
   плана, кнопка «Взять этот SIP-сервер». Запуск — tools/check_ui.py. */
UiCheck(async ({ ok, until }) => {
  const p = s => gbtParse(s).err || "ok";
  ok(p("34020000001320000008@34020000002000000001") === "ok", "строка из документации проходит");
  ok(p("gbt://34020000001320000008/50200-50210@34020000002000000001-10.0.40.246/113.125.160.58") === "ok", "полная строка: порты видео, локальный и внешний IP");
  ok(p("34020000001320000008@34020000002000000001-/113.125.160.58") === "ok", "только внешний IP, как в документации");
  ok(/20 цифр/.test(p("123@34020000002000000001")), "короткий ID устройства: " + p("123@34020000002000000001"));
  ok(/знак @/.test(p("34020000001320000008")), "нет @ и ID SIP-сервера");
  ok(/«-»/.test(p("34020000001320000008@34020000002000000001-")), "хвост «-» без адреса");
  ok(/Порт видео/.test(p("34020000001320000008/5000-4000@34020000002000000001")), "обратный диапазон портов видео");
  ok(/Локальный IP/.test(p("34020000001320000008@34020000002000000001-01.2.3.4")), "ведущий ноль в IP");

  lanOpenWizard("manual");
  changeManualVendor("GBT28181");
  const m = wizd.manual;
  ok(+m.port === 5060, "порт SIP по умолчанию 5060");
  ok(!missingManualCredentials(m), "логин и пароль GB/T не нужны: устройство не добавляется выключенным");
  ok(await until(() => Array.isArray(wizd.gbtPeers), 20000), "список устройств GB/T пришёл с сервера");
  ok(!!document.getElementById("gbtNote"), "подсказка формата под полем адреса");

  m.model = "GB28181 IPC"; m.ip = "34020000001320000008@34020000002000000001";
  ok(gbtBlock(m) === "", "первое устройство GB/T проходит");
  addManualDevice();
  ok(await until(() => !!wizd.manualAddedId, 30000), "первое устройство GB/T добавлено");
  ok(await until(() => wizd.gbtPeers?.length === 1, 30000), "сервер вернул его в списке GB/T");

  wizd.manualAddedId = null;
  m.ip = "34020000001320000009/50300@34020000002000000777";
  ok(/один SIP-сервер/.test(gbtBlock(m)), "другой SIP-сервер не проходит: " + gbtBlock(m));
  const n = addPlan.rows.length;
  planAddManual();
  ok(addPlan.rows.length === n, "«В план» не добавляет строку с другим SIP-сервером");
  renderDeviceWizard();
  ok(/Взять этот SIP-сервер/.test(document.getElementById("gbtNote")?.textContent || ""), "под полем — кнопка «Взять этот SIP-сервер»");
  gbtUseRef();
  ok(m.ip === "34020000001320000009/50300@34020000002000000001", "кнопка подставила SIP-сервер, ID и порт видео остались: " + m.ip);
  ok(gbtBlock(m) === "", "с общим SIP-сервером устройство проходит");
  m.port = 5070;
  ok(/один SIP-сервер/.test(gbtBlock(m)), "другой SIP-порт тоже не проходит");
});
